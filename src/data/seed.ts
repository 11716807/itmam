export function patientById(id: string): Patient {
  const row = overlayPatient(id) ?? PATIENTS.find((p) => p.id === id);
  if (!row) throw new Error(`Unknown patient ${id}`);
  return row;
}

export function clinicianById(id: string): Clinician {
  const row = CLINICIANS.find((c) => c.id === id);
  if (!row) throw new Error(`Unknown clinician ${id}`);
  return row;
}

export function resultById(id: string): ScreeningResult {
  const row = overlayResult(id) ?? RESULTS.find((r) => r.id === id);
  if (!row) throw new Error(`Unknown result ${id}`);
  return row;
}

export function slotById(id: string): Slot {
  const row = SLOTS.find((s) => s.id === id);
  if (!row) throw new Error(`Unknown slot ${id}`);
  return row;
}
